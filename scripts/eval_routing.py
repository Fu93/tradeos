class DailyQuotaExhausted(Exception):
    """Groq free tier tokens-per-day cap: stop the run instead of silently degrading to the keyword fallback."""


class RetryTransport(httpx.BaseTransport):
    """Retries per-minute 429s (so throttling never silently becomes a keyword fallback) and counts retries.
    A tokens-per-DAY 429 aborts the run (recorded), because waiting would take hours."""

    def __init__(self) -> None:
        self.inner = httpx.HTTPTransport()
        self.retries_429 = 0

    def handle_request(self, request: httpx.Request) -> httpx.Response:
        for _ in range(8):
            resp = self.inner.handle_request(request)
            resp.read()
            if resp.status_code != 429:
                break
            if b"per day" in resp.content:
                raise DailyQuotaExhausted(resp.json().get("error", {}).get("message", "TPD")[:200])
            self.retries_429 += 1
            time.sleep(min(float(resp.headers.get("retry-after", "10") or 10), 60) + 1)
        return resp


# ----------------------------------------------------------------------------- data
def load_set(name: str) -> list[dict]:
    if name == "original":
        base = json.loads((EVAL / "routing-dataset.json").read_text())["cases"]
        dims = {d["id"]: d for d in json.loads((EVAL / "routing-dataset-dims.json").read_text())["cases"]}
        out = []
        for c in base:
            d = dims[c["id"]]
            out.append({"id": c["id"], "message": c["message"], "lang": c["lang"], "customer": c["customer"],
                        "linked_order": c.get("linked_order"), "slice": c["tags"][0], "family": c["family"],
                        "issue_type": d["issue_type"], "customer_goal": d["customer_goal"], "mixed": d["mixed"],
                        "required_action": d["required_action"], "acceptable": d["acceptable_actions"],
                        "expected_new_task": c["expected_new_task"]})
        return out
    lab = json.loads((EVAL / "heldout-labels.json").read_text())["cases"]
    return [{"id": c["id"], "message": c["message"], "lang": c["language"], "customer": c["customer"],
             "linked_order": None, "slice": c["category"], "family": None, "issue_type": c["issue_type"],
             "customer_goal": c["customer_goal"], "mixed": c["mixed"], "required_action": c["required_action"],
             "acceptable": c["acceptable_actions"], "expected_new_task": c["required_action"] == TASK,
             "edge_case": c["edge_case"]} for c in lab]


def run(set_name: str, mode: str, cases: list[dict], delay: float, settings: Settings) -> dict:
    store = RoutingStore(str(Path(tempfile.mkdtemp()) / f"eval-{set_name}-{mode}.db"))
    store.init(reset=True)
    transport = None
    if mode == "llm":
        transport = RetryTransport()
        extractor = LLMRoutingExtractor(settings.llm_api_key, settings.llm_base_url, settings.llm_model,
                                        transport=transport)
    else:
        extractor = KeywordRoutingExtractor()
    svc = RoutingService(store, extractor, RoutingConfig())
    rows = []
    aborted = None
    for i, c in enumerate(cases):
        if mode == "llm" and i:
            time.sleep(delay)
        t0 = time.perf_counter()
        try:
            rid = svc.triage(c["message"], CaseContext(customer=c["customer"], linked_order_id=c["linked_order"]),
                             source="eval")
        except DailyQuotaExhausted as exc:
            aborted = {"at_case": c["id"], "completed": i, "reason": str(exc)}
            print(f"ABORTED at {c['id']}: {exc}", flush=True)
            break
        wall = round((time.perf_counter() - t0) * 1000, 1)
        rc = store.get_case(rid)
        ex = rc["extraction"] or {}
        f = ex.get("fields") or {}
        dec = rc["decision"] or {}
        task = store.get_task(rc["task_id"]) if rc["task_id"] else None
        new_task = bool(task) and not rc["duplicate_of_task"]
        action = REQUIRED_ACTION[rc["route"]]
        proposed = REQUIRED_ACTION.get(rc["proposed_route"])
        rows.append({
            **{k: c[k] for k in ("id", "lang", "slice", "issue_type", "customer_goal", "mixed", "required_action",
                                 "acceptable", "expected_new_task")},
            "pred_issue_raw": f.get("issue_type"), "pred_goal_raw": f.get("customer_goal"),
            "pred_mixed": f.get("mixed_goals"),
            "pred_issue": dec.get("issue_type"), "pred_goal": dec.get("customer_goal"),
            "action": action, "proposed": proposed, "demoted": proposed in AUTOMATIC and action != proposed,
            "family": dec.get("complaint_type"), "decided_by": dec.get("decided_by"),
            "confidence": rc["confidence"], "llm_confidence": ex.get("llm_confidence"), "extractor": ex.get("extractor"),
            "new_task": new_task, "duplicate_of": rc["duplicate_of_task"],
            "task_complete": task_complete(task) if new_task else None, "latency_ms": wall,
        })
        print(f"[{set_name}/{mode}] {c['id']} label={c['required_action']:<22} got={action:<22} "
              f"{f.get('issue_type')}/{f.get('customer_goal')} conf={rc['confidence']} {'NEW TASK' if new_task else ''}",
              flush=True)
    with store.connect() as conn:
        dup_open = conn.execute("SELECT COUNT(*) FROM (SELECT dedup_key FROM supplier_tasks WHERE status='DRAFT_READY' "
                                "GROUP BY dedup_key HAVING COUNT(*) > 1)").fetchone()[0]
    return {"meta": {"mode": mode, "extractor": getattr(extractor, "name", mode), "aborted": aborted,
                     "n_planned": len(cases), "n_completed": len(rows),
                     "run_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
                     "keys_with_more_than_one_open_task": dup_open,
                     "retries_429": transport.retries_429 if transport else 0,
                     "llm_fallbacks": sum("unavailable" in (r["extractor"] or "") for r in rows),
                     "delay_s": delay if mode == "llm" else 0},
            "rows": rows}


# ----------------------------------------------------------------------------- metrics
def wilson(k: int, n: int) -> tuple[float, float] | None:
    if not n:
        return None
    z, p = 1.96, k / n
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return round(100 * max(0, centre - half), 1), round(100 * min(1, centre + half), 1)


def frac(k: int, n: int, ci: bool = False) -> str:
    if not n:
        return "n/a (0/0)"
    s = f"{k}/{n} ({100 * k / n:.1f}%)"
    if ci:
        lo, hi = wilson(k, n)
        s += f" [95% CI {lo}–{hi}%]"
    return s


def score(rows: list[dict]) -> dict:
    n = len(rows)
    trig = [r for r in rows if r["action"] == TASK]
    need = [r for r in rows if r["required_action"] == TASK]
    non = [r for r in rows if r["required_action"] != TASK]
    manual = [r for r in rows if r["required_action"] in (HUMAN, CLARIFY)]
    dups = [r for r in rows if r["slice"] == "duplicate"]
    tasks = [r for r in rows if r["new_task"]]
    return {
        "n": n,
        "issue_type": [sum(r["pred_issue"] == r["issue_type"] for r in rows), n],
        "issue_type_raw_ai": [sum(r["pred_issue_raw"] == r["issue_type"] for r in rows), n],
        "customer_goal": [sum(r["pred_goal"] == r["customer_goal"] for r in rows), n],
        "customer_goal_raw_ai": [sum(r["pred_goal_raw"] == r["customer_goal"] for r in rows), n],
        "mixed_flag": [sum(bool(r["pred_mixed"]) == bool(r["mixed"]) for r in rows), n],
        "action_strict": [sum(r["action"] == r["required_action"] for r in rows), n],
        "action_lenient": [sum(r["action"] in r["acceptable"] for r in rows), n],
        "all_three_strict": [sum(r["pred_issue"] == r["issue_type"] and r["pred_goal"] == r["customer_goal"]
                                 and r["action"] == r["required_action"] for r in rows), n],
        "task_precision": [sum(r["required_action"] == TASK for r in trig), len(trig)],
        "task_recall": [sum(r["action"] == TASK for r in need), len(need)],
        "task_recall_incl_human_confirm": [sum(r["action"] == TASK or r["proposed"] == TASK for r in need), len(need)],
        "false_trigger_non_task": [sum(r["action"] == TASK for r in non), len(non)],
        "automated_but_should_be_manual": [sum(r["action"] in AUTOMATIC for r in manual), len(manual)],
        "duplicate_new_task": [sum(r["new_task"] for r in dups), len(dups)],
        "completeness": [sum(bool(r["task_complete"]) for r in tasks), len(tasks)],
        "demoted": [sum(r["demoted"] for r in rows), n],
        "latency_p50": statistics.median([r["latency_ms"] for r in rows]) if rows else None,
        "confusion": {f"{e} -> {g}": k for (e, g), k in
                      sorted(Counter((r["required_action"], r["action"]) for r in rows).items())},
        "false_triggers": [r["id"] for r in trig if r["required_action"] != TASK],
        "missed_triggers": [r["id"] for r in need if r["action"] != TASK],
        "automated_manual_ids": [r["id"] for r in manual if r["action"] in AUTOMATIC],
    }


def confidence_analysis(rows: list[dict]) -> dict:
    """Does the (uncalibrated) LLM self-report separate right from wrong at all?"""
    rs = [r for r in rows if r["llm_confidence"] is not None]

    def summary(vals):
        if not vals:
            return None
        v = sorted(vals)
        return {"n": len(v), "min": v[0], "p25": v[len(v) // 4], "median": statistics.median(v), "max": v[-1],
                "mean": round(statistics.mean(v), 3)}

    out = {"n_with_confidence": len(rs)}
    for name, wrong_fn in (("action_wrong", lambda r: r["action"] not in r["acceptable"]),
                           ("any_dimension_wrong", lambda r: r["action"] not in r["acceptable"]
                            or r["pred_issue"] != r["issue_type"] or r["pred_goal"] != r["customer_goal"])):
        right = [r["llm_confidence"] for r in rs if not wrong_fn(r)]
        wrong = [r["llm_confidence"] for r in rs if wrong_fn(r)]
        pairs = [(w, g) for w in wrong for g in right]
        auc = (sum(1.0 if g > w else 0.5 if g == w else 0.0 for w, g in pairs) / len(pairs)) if pairs else None
        thresholds = {}
        for t in (0.80, 0.85, 0.90, 0.95, 0.99):
            thresholds[str(t)] = {"wrong_below": [sum(w < t for w in wrong), len(wrong)],
                                  "right_below": [sum(g < t for g in right), len(right)]}
        buckets = {}
        for lo, hi in ((0, .8), (.8, .9), (.9, .95), (.95, .99), (.99, 1.01)):
            b = [r for r in rs if lo <= r["llm_confidence"] < hi]
            buckets[f"[{lo}, {min(hi, 1.0)}{']' if hi > 1 else ')'}"] = [sum(not wrong_fn(r) for r in b), len(b)]
        out[name] = {"right": summary(right), "wrong": summary(wrong),
                     "auc_right_above_wrong": None if auc is None else round(auc, 3),
                     "thresholds": thresholds, "buckets_right_of_n": buckets}
    return out


def breakdown(rows, key, values) -> dict:
    return {v: score([r for r in rows if r[key] == v]) for v in values if any(r[key] == v for r in rows)}


# ----------------------------------------------------------------------------- report
def p(x, ci=False) -> str:
    return frac(*x, ci=ci)


SET_TITLE = {"original": "Original 100 — regression set of known scenarios (author-written)",
             "heldout": "Held-out 60 — unseen, blind-generated (qwen/qwen3.8-27b), author-labelled, pending human review"}


def markdown(res: dict) -> str:
    L = ["# Supplier routing eval — round 2 (rules `" + res["rule_version"] + "`)", "",
         "Two sets, reported **separately** (never pooled). Every rate is `correct/n (%)`; key rates carry a Wilson "
         "95% confidence interval. Extractor model: `" + res["model"] + "` (Groq). All operational data is MOCK.",
         "Round-1 history: [routing-results-round1-rules011.md](routing-results-round1-rules011.md), "
         "[routing-results-run1.md](routing-results-run1.md).", ""]
    for set_name, sres in res["sets"].items():
        L += [f"## {SET_TITLE[set_name]}", ""]
        for mode, m in sres["runs"].items():
            mt = m["meta"]
            if mt.get("aborted"):
                L.append(f"* **{mode}: PARTIAL RUN** — {mt['n_completed']}/{mt['n_planned']} cases, stopped at "
                         f"{mt['aborted']['at_case']} (Groq free-tier tokens-per-day cap). Metrics below cover only "
                         "the completed rows.")
            L.append(f"* **{mode}** run {mt['run_at']} UTC · extractor `{mt['extractor']}` · 429 retries "
                     f"{mt['retries_429']} · LLM fallbacks {mt['llm_fallbacks']} · keys with >1 open task "
                     f"{mt['keys_with_more_than_one_open_task']}")
        modes = list(sres["runs"])
        L += ["", "| Metric | " + " | ".join(modes) + " |", "| --- | " + " | ".join("---" for _ in modes) + " |"]
        spec = [("issue_type accuracy (after text checks)", "issue_type", True),
                ("issue_type accuracy (raw AI output)", "issue_type_raw_ai", False),
                ("customer_goal accuracy (after text checks)", "customer_goal", True),
                ("customer_goal accuracy (raw AI output)", "customer_goal_raw_ai", False),
                ("mixed flag accuracy", "mixed_flag", False),
                ("required_action strict", "action_strict", True),
                ("required_action lenient (acceptable_actions)", "action_lenient", True),
                ("all three dimensions right (strict)", "all_three_strict", False),
                ("supplier-task precision", "task_precision", True),
                ("supplier-task recall (automatic)", "task_recall", True),
                ("supplier-task recall incl. human-confirm proposal", "task_recall_incl_human_confirm", False),
                ("false trigger on non-task cases", "false_trigger_non_task", True),
                ("should be human/clarify but automated", "automated_but_should_be_manual", True),
                ("duplicate rows that created a new task", "duplicate_new_task", False),
                ("task draft completeness", "completeness", False),
                ("automatic actions demoted by confidence", "demoted", False)]
        for label, key, ci in spec:
            L.append(f"| {label} | " + " | ".join(p(sres["runs"][mo]["overall"][key], ci) for mo in modes) + " |")
        L.append("| latency p50 per case (ms) | " + " | ".join(str(sres["runs"][mo]["overall"]["latency_p50"])
                                                           for mo in modes) + " |")
        for mode, m in sres["runs"].items():
            o = m["overall"]
            L += ["", f"### {set_name} / {mode}: breakdowns", "",
                  "| Slice | n | issue_type | customer_goal | action lenient | tasks created | false triggers |",
                  "| --- | --- | --- | --- | --- | --- | --- |"]
            for k, s in m["by_slice"].items():
                L.append(f"| {k} | {s['n']} | {p(s['issue_type'])} | {p(s['customer_goal'])} | {p(s['action_lenient'])} "
                         f"| {s['task_precision'][1]} | {len(s['false_triggers'])} |")
            L += ["", "| Language | n | issue_type | customer_goal | action lenient | false triggers |",
                  "| --- | --- | --- | --- | --- | --- |"]
            for k, s in m["by_lang"].items():
                L.append(f"| {k} | {s['n']} | {p(s['issue_type'])} | {p(s['customer_goal'])} | {p(s['action_lenient'])} "
                         f"| {len(s['false_triggers'])} |")
            L += ["", "Confusion (label → system action): " + "; ".join(f"{k}: {v}" for k, v in o["confusion"].items()), ""]
            rows = {r["id"]: r for r in m["rows"]}

            def tab(title, ids):
                out = ["", f"**{title} ({len(ids)})**", ""]
                if not ids:
                    return out + ["none"]
                out += ["| id | lang | label issue/goal/action | system issue/goal → action | conf | decided by |",
                        "| --- | --- | --- | --- | --- | --- |"]
                for i in ids:
                    r = rows[i]
                    out.append(f"| {i} | {r['lang']} | {r['issue_type']}/{r['customer_goal']}{'/mixed' if r['mixed'] else ''}"
                               f" → {r['required_action']} | {r['pred_issue']}/{r['pred_goal']}"
                               f"{'/mixed' if r['pred_mixed'] else ''} → {r['action']} | {r['confidence']} | "
                               f"{(r['decided_by'] or '').replace('|', '/')[:220]} |")
                return out
            L += tab("False triggers (supplier task created, label says no task)", o["false_triggers"])
            L += tab("Missed triggers (label says task, none created)", o["missed_triggers"])
            L += tab("Should have gone to a human / clarification but was automated", o["automated_manual_ids"])
            wrong_action = [r["id"] for r in m["rows"] if r["action"] not in r["acceptable"]
                            and r["id"] not in o["false_triggers"] + o["missed_triggers"] + o["automated_manual_ids"]]
            L += tab("Other required_action errors (outside acceptable_actions)", wrong_action)
            dim_wrong = [r["id"] for r in m["rows"] if (r["pred_issue"] != r["issue_type"]
                                                        or r["pred_goal"] != r["customer_goal"])]
            L += tab("Dimension misclassifications (issue_type or customer_goal ≠ label; route may still be right)",
                     dim_wrong)
            if m.get("confidence"):
                L += confidence_md(m["confidence"])
        L.append("")
    L += ["## Reading these numbers", "", res.get("notes", "")]
    return "\n".join(L) + "\n"


def confidence_md(c: dict) -> list[str]:
    L = ["", f"**Confidence analysis (LLM self-report; {c['n_with_confidence']} rows with a confidence)**", ""]
    for name in ("action_wrong", "any_dimension_wrong"):
        a = c[name]
        L.append(f"* *{name.replace('_', ' ')}*: right {a['right']} · wrong {a['wrong']} · "
                 f"P(conf right > conf wrong) = {a['auc_right_above_wrong']} (0.5 = no separation)")
        L.append("  * below threshold t → demoted: " + "; ".join(
            f"t={t}: wrong {v['wrong_below'][0]}/{v['wrong_below'][1]}, right {v['right_below'][0]}/{v['right_below'][1]}"
            for t, v in a["thresholds"].items()))
        L.append("  * right/n per bucket: " + "; ".join(f"{k}: {v[0]}/{v[1]}" for k, v in a["buckets_right_of_n"].items()))
    return L


def finalize(res: dict) -> None:
    for sres in res["sets"].values():
        for m in sres["runs"].values():
            m["overall"] = score(m["rows"])
            m["by_slice"] = breakdown(m["rows"], "slice", sorted({r["slice"] for r in m["rows"]}))
            m["by_lang"] = breakdown(m["rows"], "lang", LANGS)
            m["confidence"] = confidence_analysis(m["rows"]) if m["meta"]["mode"] == "llm" else None
    res["notes"] = (EVAL / "routing-results-notes.md").read_text() if (EVAL / "routing-results-notes.md").exists() else ""
    OUT_JSON.write_text(json.dumps(res, ensure_ascii=False, indent=1))
    OUT_MD.write_text(markdown(res))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", choices=("original", "heldout", "both"), default="both")
    ap.add_argument("--mode", choices=("llm", "keyword", "both"), default="both")
    ap.add_argument("--delay", type=float, default=6.0, help="seconds between LLM calls (Groq free tier)")
    ap.add_argument("--out", default=str(OUT_JSON))
    ap.add_argument("--rescore", action="store_true")
    args = ap.parse_args()
    if args.rescore:
        finalize(json.loads(OUT_JSON.read_text()))
        return
    load_dotenv()
    settings = Settings.from_env()
    sets = ["original", "heldout"] if args.set == "both" else [args.set]
    modes = ["llm", "keyword"] if args.mode == "both" else [args.mode]
    if "llm" in modes and not settings.llm_configured:
        sys.exit("LLM_API_KEY not set (use --mode keyword)")
    res = json.loads(OUT_JSON.read_text()) if OUT_JSON.exists() else {}
    if res.get("rule_version") != RULE_VERSION:
        res = {}
    res.setdefault("rule_version", RULE_VERSION)
    res["model"] = settings.llm_model
    res.setdefault("sets", {})
    for s in sets:
        cases = load_set(s)
        res["sets"].setdefault(s, {"runs": {}})
        for mode in modes:
            res["sets"][s]["runs"][mode] = run(s, mode, cases, args.delay, settings)
            OUT_JSON.write_text(json.dumps(res, ensure_ascii=False, indent=1))  # checkpoint
    finalize(res)
    for s, sres in res["sets"].items():
        for mo, m in sres["runs"].items():
            o = m["overall"]
            print(s, mo, {k: o[k] for k in ("issue_type", "customer_goal", "action_lenient", "task_precision",
                                            "task_recall", "false_trigger_non_task", "automated_but_should_be_manual")})


if __name__ == "__main__":
    main()
